namespace OnlineChatWithSignalR.Data;

public sealed class ChatRoom
{
    public const int NameMaxLength = 100;

    public Guid Id { get; set; }
    public required string Name { get; set; }
    public required string CreatedByUserId { get; set; }
    public DateTime CreatedAt { get; set; }

    public List<RoomMember> Members { get; set; } = [];
}

public sealed class RoomMember
{
    public Guid RoomId { get; set; }
    public required string UserId { get; set; }
    public DateTime JoinedAt { get; set; }

    public ChatRoom Room { get; set; } = null!;
    public ChatUser User { get; set; } = null!;
}

public sealed class ChatMessage
{
    public const int ContentMaxLength = 2000;

    /// <summary>Generated by the client, so a retried send can be recognized as a duplicate.</summary>
    public Guid Id { get; set; }

    /// <summary>
    /// Assigned by the database in insert order. Gives messages a strict order (timestamps can tie)
    /// and is used as the cursor for paging through history.
    /// </summary>
    public long Sequence { get; set; }

    public Guid RoomId { get; set; }
    public required string SenderId { get; set; }
    public required string Content { get; set; }
    public DateTime SentAt { get; set; }

    public ChatRoom Room { get; set; } = null!;
    public ChatUser Sender { get; set; } = null!;
}
