using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;

namespace OnlineChatWithSignalR.Data;

public sealed class ChatDbContext(DbContextOptions<ChatDbContext> options)
    : IdentityDbContext<ChatUser>(options)
{
    public DbSet<ChatRoom> Rooms => Set<ChatRoom>();
    public DbSet<RoomMember> RoomMembers => Set<RoomMember>();
    public DbSet<ChatMessage> Messages => Set<ChatMessage>();

    protected override void OnModelCreating(ModelBuilder builder)
    {
        base.OnModelCreating(builder);

        builder.Entity<ChatRoom>(room =>
        {
            room.ToTable("Rooms");
            room.Property(r => r.Name).HasMaxLength(ChatRoom.NameMaxLength);
            room.HasIndex(r => r.Name).IsUnique();
            room.Property(r => r.CreatedByUserId).HasMaxLength(450);
        });

        builder.Entity<RoomMember>(member =>
        {
            member.ToTable("RoomMembers");
            member.HasKey(m => new { m.RoomId, m.UserId });
            member.HasOne(m => m.Room).WithMany(r => r.Members).HasForeignKey(m => m.RoomId);
            member.HasOne(m => m.User).WithMany().HasForeignKey(m => m.UserId);
            // Used on connect to find all rooms of a user
            member.HasIndex(m => m.UserId);
        });

        builder.Entity<ChatMessage>(message =>
        {
            message.ToTable("Messages");
            // The id is generated by the client, never by the database
            message.Property(m => m.Id).ValueGeneratedNever();
            message.Property(m => m.Content).HasMaxLength(ChatMessage.ContentMaxLength);
            message.HasOne(m => m.Room).WithMany().HasForeignKey(m => m.RoomId);
            message.HasOne(m => m.Sender).WithMany().HasForeignKey(m => m.SenderId);
            message.Property(m => m.Sequence).UseIdentityAlwaysColumn();
            // Supports "latest messages of a room" and cursor paging by sequence
            message.HasIndex(m => new { m.RoomId, m.Sequence });
        });
    }
}
